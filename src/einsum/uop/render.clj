(ns einsum.uop.render
  "Linearizer & CStyle Source Renderer for rangeified UOp kernels.
   Modeled on tinygrad's `CStyleLanguage` / `HIPRenderer` (`tinygrad/renderer/cstyle.py`)
   and geohot's ML compiler syllabus (Weeks 2, 6, 7).
   Renders optimized, rangeified UOp kernels into standalone C99 (for `:uop-cpu`)
   or HIP C++ (for `:uop-rocm` / `gfx1100`) source strings."
  (:require [clojure.string :as str]
            [einsum.uop.core :as uop]
            [einsum.uop.rangeify :as rangeify]))

;; -----------------------------------------------------------------------------
;; 1. C / HIP Type & Literal Formatting
;; -----------------------------------------------------------------------------

(defn- dtype->c-type [dtype]
  (case dtype
    (:bool :i1) "int"
    :i8 "signed char"
    :u8 "unsigned char"
    :i16 "short"
    :u16 "unsigned short"
    :i32 "int"
    :u32 "unsigned int"
    :i64 "long long"
    :u64 "unsigned long long"
    :f16 "_Float16"
    :bf16 "__bf16"
    :f32 "float"
    :f64 "double"
    "float"))

(defn- format-const-literal [dtype val]
  (cond
    (contains? #{:bool :i1} dtype)
    (if val "1" "0")

    (contains? #{:f16 :bf16 :f32} dtype)
    (let [d (double val)]
      (cond
        (Double/isNaN d) "(0.0f/0.0f)"
        (Double/isInfinite d) (if (pos? d) "(1.0f/0.0f)" "(-1.0f/0.0f)")
        :else (let [s (str (float d))]
                (if (or (str/includes? s ".") (str/includes? s "E") (str/includes? s "e"))
                  (str s "f")
                  (str s ".0f")))))

    (= dtype :f64)
    (str (double val))

    :else
    (str (long val))))

;; -----------------------------------------------------------------------------
;; 2. Buffer Slot & Constant Table Discovery
;; -----------------------------------------------------------------------------

(defn- collect-referenced-slots
  "Collects all referenced global/param `:uop/buffer` slots in topological order,
   ensuring `out-slot` is always included."
  [sink-uop out-slot out-dtype]
  (let [nodes (uop/toposort sink-uop)
        buf-nodes (filter #(= :uop/buffer (:op %)) nodes)
        slot-map (reduce
                  (fn [acc b]
                    (let [slot (:slot (:arg b))]
                      (if (= :vconst (:device (:arg b)))
                        acc
                        (assoc acc slot {:slot slot :dtype (:dtype b)}))))
                  {out-slot {:slot out-slot :dtype out-dtype}}
                  buf-nodes)]
    (vec (sort-by :slot (vals slot-map)))))

;; -----------------------------------------------------------------------------
;; 3. Expression & Statement Code Generator
;; -----------------------------------------------------------------------------

(defn- sanitize-ident [s]
  (str/replace (str s) #"[^a-zA-Z0-9_]" "_"))

(defn render-kernel
  "Renders an optimized kernel map (from `einsum.uop.opt/optimize-kernel` or `schedule-graph`)
   into a standalone C99 (`:target :cpu`) or HIP C++ (`:target :rocm`) program map:
   `{:fn-name string
     :target (:cpu | :rocm)
     :source string
     :buffer-slots [slot0 slot1 ...]
     :buffer-dtypes [dt0 dt1 ...]
     :global-size [gx gy gz]
     :local-size [lx ly lz]}`."
  ([kernel-entry]
   (render-kernel kernel-entry {:target :rocm}))
  ([kernel-entry {:keys [target] :or {target :rocm}}]
   (let [rk (:rangeified kernel-entry)
         {:keys [sink val-expr out-ranges out-shape out-dtype out-size out-slot vconsts]} rk
         fn-name (sanitize-ident (or (:name kernel-entry) (str "uop_kernel_" out-slot)))
         slot-infos (collect-referenced-slots sink out-slot out-dtype)
         buffer-slots (mapv :slot slot-infos)
         buffer-dtypes (mapv :dtype slot-infos)
         out-lin-idx-uop (rangeify/coords->linear-index out-ranges out-shape)
         local-threads (long (first (or (:local-size kernel-entry)
                                        (if (= target :cpu) [1 1 1] [256 1 1]))))
         grid-blocks (if (= target :cpu)
                       1
                       (long (quot (+ (long out-size) local-threads -1) local-threads)))

         sb (StringBuilder.)
         var-names (java.util.HashMap.)
         vconst-names (into {} (map (fn [{:keys [slot]}] [slot (str "vc_" slot)]) vconsts))
         ssa-counter (atom 0)]

     ;; 1. Emit Preamble / Math Intrinsics
     (if (= target :rocm)
       (do
         (.append sb "// Generated by clj-einsum UOp HIPRenderer (gfx1100)\n")
         (.append sb "#ifndef INFINITY\n#define INFINITY (1.0f/0.0f)\n#endif\n"))
       (do
         (.append sb "// Generated by clj-einsum UOp C99Renderer\n")
         (.append sb "#include <math.h>\n#include <stdint.h>\n\n")))

     ;; 2. Emit static vconst tables (e.g. RoPE cos/sin, causal mask)
     (doseq [{:keys [slot values dtype size]} vconsts]
       (let [c-type (dtype->c-type dtype)
             qualifier (if (= target :rocm) "__constant__ " "static const ")
             lits (str/join ", " (map #(format-const-literal dtype %) values))]
         (.append sb (format "%s%s vc_%d[%d] = {%s};\n" qualifier c-type (long slot) (long size) lits))))

     ;; 3. Emit Function Signature
     ;; For universal FFM invocation (zero arity combinatorial explosion), we emit BOTH:
     ;; - Direct typed pointer parameters `buf_<slot>` for HIP (`hipModuleLaunchKernel` passes `void** kernelParams`)
     ;; - And for CPU, a single `void** buffers` wrapper `fn_name_entry(void** buffers)` so Panama FFM uses 1 static FunctionDescriptor!
     (let [param-decls (str/join ", "
                                 (map (fn [{:keys [slot dtype]}]
                                        (format "%s* __restrict__ buf_%d" (dtype->c-type dtype) (long slot)))
                                      slot-infos))]
       (if (= target :rocm)
         (.append sb (format "\nextern \"C\" __global__ void %s(%s) {\n" fn-name param-decls))
         (.append sb (format "\nstatic inline void %s_impl(%s) {\n" fn-name param-decls))))

     ;; 4. Bind Output Loop Coordinates
     ;; Map flat linear output index `gidx` into `out-ranges` via div/mod strides
     (if (= target :rocm)
       (do
         (.append sb (format "  int gidx = (int)(blockIdx.x * %d + threadIdx.x);\n" local-threads))
         (.append sb (format "  if (gidx >= %d) return;\n" (long out-size))))
       (.append sb (format "  for (int gidx = 0; gidx < %d; ++gidx) {\n" (long out-size))))

     (let [indent (if (= target :rocm) "  " "    ")
           strides (rangeify/row-major-strides out-shape)]
       (doseq [[r dim stride] (map vector out-ranges out-shape strides)]
         (when (= :uop/range (:op r))
           (let [r-var (str "r_" (:axis (:arg r)))
                 d (long dim)
                 s (long stride)]
             (.put var-names (:id r) r-var)
             (if (== 1 s)
               (.append sb (format "%sint %s = (gidx %% %d);\n" indent r-var d))
               (.append sb (format "%sint %s = ((gidx / %d) %% %d);\n" indent r-var s d))))))

       ;; 5. Recursive SSA Emitter for `val-expr` and `out-lin-idx-uop`
       (letfn [(emit-expr [node cur-indent]
                 (if-let [existing (.get var-names (:id node))]
                   existing
                   (let [{:keys [op dtype src arg]} node
                         c-type (dtype->c-type dtype)]
                     (case op
                       :uop/const
                       (format-const-literal dtype arg)

                       :uop/load
                       (let [idx-uop (first src)
                             buf-uop (first (:src idx-uop))
                             lin-uop (second (:src idx-uop))
                             slot (:slot (:arg buf-uop))
                             buf-name (or (get vconst-names slot) (str "buf_" slot))
                             idx-expr (emit-expr lin-uop cur-indent)
                             v-name (str "v_" (swap! ssa-counter inc))]
                         (.append sb (format "%s%s %s = %s[%s];\n" cur-indent c-type v-name buf-name idx-expr))
                         (.put var-names (:id node) v-name)
                         v-name)

                       :uop/reduce-axis
                       (let [body-uop (first src)
                             r-uops (rest src)
                             red-op (:op arg)
                             acc-name (str "acc_" (swap! ssa-counter inc))
                             init-lit (case red-op
                                        :max "(-1.0e30f)"
                                        :min "(1.0e30f)"
                                        (format-const-literal dtype 0))]
                         (.append sb (format "%s%s %s = %s;\n" cur-indent c-type acc-name init-lit))
                         ;; Open nested reduction loops
                         (doseq [[depth r] (map-indexed vector r-uops)]
                           (let [loop-indent (str cur-indent (apply str (repeat depth "  ")))
                                 r-var (str "rk_" (:axis (:arg r)))
                                 bound-expr (emit-expr (first (:src r)) loop-indent)]
                             (.put var-names (:id r) r-var)
                             (.append sb (format "%s#pragma unroll 4\n" loop-indent))
                             (.append sb (format "%sfor (int %s = 0; %s < %s; ++%s) {\n"
                                                 loop-indent r-var r-var bound-expr r-var))))
                         ;; Emit reduction body inside innermost loop
                         (let [inner-indent (str cur-indent (apply str (repeat (count r-uops) "  ")))
                               body-val (emit-expr body-uop inner-indent)]
                           (case red-op
                             :max (.append sb (format "%s%s = (%s > %s) ? %s : %s;\n"
                                                      inner-indent acc-name body-val acc-name body-val acc-name))
                             :min (.append sb (format "%s%s = (%s < %s) ? %s : %s;\n"
                                                      inner-indent acc-name body-val acc-name body-val acc-name))
                             (.append sb (format "%s%s += %s;\n" inner-indent acc-name body-val))))
                         ;; Close reduction loops
                         (doseq [depth (reverse (range (count r-uops)))]
                           (let [loop-indent (str cur-indent (apply str (repeat depth "  ")))]
                             (.append sb (format "%s}\n" loop-indent))))
                         (.put var-names (:id node) acc-name)
                         acc-name)

                       ;; Elementwise Unary / Binary / Ternary ALU Ops
                       (let [child-exprs (mapv #(emit-expr % cur-indent) src)
                             [e0 e1 e2] child-exprs
                             rhs-code (case op
                                        :uop/neg (format "(-%s)" e0)
                                        :uop/recip (format "(1.0f / %s)" e0)
                                        :uop/exp2 (format "exp2f(%s)" e0)
                                        :uop/log2 (format "log2f(%s)" e0)
                                        :uop/sin (format "sinf(%s)" e0)
                                        :uop/sqrt (format "sqrtf(%s)" e0)
                                        :uop/trunc (format "truncf(%s)" e0)
                                        :uop/cast (format "((%s)(%s))" (dtype->c-type arg) e0)
                                        :uop/add (format "(%s + %s)" e0 e1)
                                        :uop/sub (format "(%s - %s)" e0 e1)
                                        :uop/mul (format "(%s * %s)" e0 e1)
                                        :uop/div (format "(%s / %s)" e0 e1)
                                        :uop/idiv (format "(%s / %s)" e0 e1)
                                        :uop/mod (format "(%s %% %s)" e0 e1)
                                        :uop/max (format "((%s > %s) ? %s : %s)" e0 e1 e0 e1)
                                        :uop/min (format "((%s < %s) ? %s : %s)" e0 e1 e0 e1)
                                        :uop/shl (format "(%s << %s)" e0 e1)
                                        :uop/shr (format "((unsigned int)%s >> %s)" e0 e1)
                                        :uop/and (if (contains? #{:bool :i1} (:dtype (first src)))
                                                   (format "(%s && %s)" e0 e1)
                                                   (format "(%s & %s)" e0 e1))
                                        :uop/or (if (contains? #{:bool :i1} (:dtype (first src)))
                                                  (format "(%s || %s)" e0 e1)
                                                  (format "(%s | %s)" e0 e1))
                                        :uop/xor (format "(%s ^ %s)" e0 e1)
                                        :uop/cmplt (format "(%s < %s)" e0 e1)
                                        :uop/cmple (format "(%s <= %s)" e0 e1)
                                        :uop/cmpeq (format "(%s == %s)" e0 e1)
                                        :uop/cmpne (format "(%s != %s)" e0 e1)
                                        :uop/cmpgt (format "(%s > %s)" e0 e1)
                                        :uop/cmpge (format "(%s >= %s)" e0 e1)
                                        :uop/where (format "(%s ? %s : %s)" e0 e1 e2)
                                        (throw (ex-info "Unsupported UOp in CStyle renderer" {:op op :node node})))
                             v-name (str "v_" (swap! ssa-counter inc))]
                         (.append sb (format "%s%s %s = %s;\n" cur-indent c-type v-name rhs-code))
                         (.put var-names (:id node) v-name)
                         v-name)))))]
         (let [final-val-var (emit-expr val-expr indent)
               out-idx-var (emit-expr out-lin-idx-uop indent)]
           (.append sb (format "%sbuf_%d[%s] = %s;\n" indent out-slot out-idx-var final-val-var)))))

     ;; 6. Close loop / function body and emit uniform void** entry wrapper for CPU
     (if (= target :rocm)
       (.append sb "}\n")
       (let [unpacked-args (str/join ", "
                                     (map-indexed
                                      (fn [idx {:keys [dtype]}]
                                        (format "(%s*)buffers[%d]" (dtype->c-type dtype) idx))
                                      slot-infos))]
         (.append sb "  }\n}\n\n")
         (.append sb (format "void %s(void** buffers) {\n  %s_impl(%s);\n}\n"
                             fn-name fn-name unpacked-args))))

     {:fn-name fn-name
      :target target
      :source (.toString sb)
      :buffer-slots buffer-slots
      :buffer-dtypes buffer-dtypes
      :global-size [grid-blocks 1 1]
      :local-size [local-threads 1 1]})))
